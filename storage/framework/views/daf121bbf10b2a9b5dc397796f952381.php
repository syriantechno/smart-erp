    <script>
        document.addEventListener('DOMContentLoaded', function () {
            const jq = window.jQuery || window.$;
            if (!jq) {
                console.error('jQuery is not loaded; warehouse create modal scripts will not run.');
                return;
            }

            jq('#create-warehouse-form').on('submit', function (e) {
                e.preventDefault();

                const formData = new FormData(this);
                const submitBtn = jq('#create-warehouse-btn');
                const originalText = submitBtn.html();

                submitBtn.prop('disabled', true).html('<i class="w-4 h-4 mr-2 animate-spin" data-lucide="loader"></i> Saving...');

                jq.ajax({
                    url: '<?php echo e(route("warehouse.warehouses.store")); ?>',
                    type: 'POST',
                    data: formData,
                    processData: false,
                    contentType: false,
                    headers: {
                        'X-CSRF-TOKEN': document.querySelector("meta[name='csrf-token']").getAttribute('content')
                    },
                    success: function (response) {
                        if (response.success) {
                            const modalEl = document.getElementById('create-warehouse-modal');
                            if (modalEl && typeof tailwind !== 'undefined' && tailwind.Modal) {
                                const instance = tailwind.Modal.getOrCreateInstance(modalEl);
                                instance.hide();
                            }

                            const form = document.getElementById('create-warehouse-form');
                            if (form) {
                                form.reset();
                            }

                            if (window.warehousesTable) {
                                window.warehousesTable.ajax.reload();
                            }

                            if (typeof window.showSuccess === 'function') {
                                window.showSuccess(response.message || 'Warehouse created successfully');
                            }
                        } else if (typeof window.showError === 'function') {
                            window.showError(response.message || 'Failed to create warehouse.');
                        }
                    },
                    error: function (xhr) {
                        let errors = xhr.responseJSON?.errors || {};
                        let errorMessage = xhr.responseJSON?.message || 'An error occurred';

                        if (Object.keys(errors).length > 0) {
                            errorMessage = Object.values(errors).flat().join('\n');
                        }

                        if (typeof window.showError === 'function') {
                            window.showError(errorMessage);
                        }
                    },
                    complete: function () {
                        submitBtn.prop('disabled', false).html(originalText);
                        if (typeof window.lucide !== 'undefined' && window.lucide.createIcons) {
                            window.lucide.createIcons();
                        }
                    }
                });
            });
        });
    </script>
